"""
state.py
========
LangGraph TypedDict state definition for the PS137 Agricultural
Scenario Coordinator agent graph.
"""

from typing import Annotated, List, Optional, TypedDict

from langgraph.graph.message import add_messages


class AgentState(TypedDict):
    """
    Shared state threaded through every node in the LangGraph workflow.

    Fields
    ------
    messages
        Full conversation history, managed by LangGraph's add_messages reducer.
    user_request
        The raw text of the user's current request.
    intent
        Classified intent: one of
        "historical_analysis" | "scenario_simulation" | "comparison" |
        "clarification_needed" | "invalid"
    extraction_result
        ExtractionResult serialised as a plain dict (use ExtractionResult.model_dump()).
    scenarios
        List of ScenarioAssumption dicts (use ScenarioAssumption.model_dump()).
    needs_clarification
        True when the extraction agent determined more info is required.
    clarification_question
        The question to surface to the user when needs_clarification is True.
    baseline_results
        List of baseline lookup result dicts (from historical_analysis module).
    simulation_results
        List of scenario result dicts (from scenario_engine module).
    validation_results
        List of validation result dicts (from scenario_validator module).
    comparison_result
        Comparison result dict (from scenario_comparison module), or None.
    explanation
        Human-readable explanation generated by the explanation node.
    final_output
        The fully assembled response dict ready for the UI layer.
    error
        Error message string if any node encountered a fatal error, else None.
    workflow_stage
        Name of the graph node currently being (or last) executed.
    """

    messages: Annotated[list, add_messages]
    user_request: str
    intent: Optional[str]
    extraction_result: Optional[dict]   # ExtractionResult as dict
    scenarios: List[dict]               # list of ScenarioAssumption as dicts
    needs_clarification: bool
    clarification_question: Optional[str]
    baseline_results: List[dict]
    simulation_results: List[dict]
    validation_results: List[dict]
    comparison_result: Optional[dict]
    explanation: Optional[str]
    final_output: Optional[dict]
    error: Optional[str]
    workflow_stage: str                 # current stage name
